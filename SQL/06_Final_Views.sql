--------------------------------------------------Claims Summary View-------------------------------------------------

CREATE OR REPLACE VIEW CLAIMS_SUMMARY_VW AS
SELECT
    COUNT(*) AS TOTAL_CLAIMS,
    ROUND(SUM(CLAIM_AMOUNT), 2) AS TOTAL_CLAIM_AMOUNT,
    ROUND(AVG(CLAIM_AMOUNT), 2) AS AVG_CLAIM_AMOUNT,
    ROUND(MEDIAN(CLAIM_AMOUNT), 2) AS MEDIAN_CLAIM_AMOUNT,
    ROUND(SUM(PREMIUM_AMOUNT), 2) AS TOTAL_PREMIUM,
    ROUND(AVG(PREMIUM_AMOUNT), 2) AS AVG_PREMIUM,
    ROUND(AVG(CLAIM_TO_PREMIUM_RATIO), 2) AS AVG_CLAIM_TO_PREMIUM_RATIO,
    ROUND(AVG(REPORTING_DELAY_DAYS), 2) AS AVG_REPORTING_DELAY_DAYS,
    COUNT_IF(REPORTING_DELAY_DAYS = 0) AS SAME_DAY_CLAIMS,
    ROUND(COUNT_IF(REPORTING_DELAY_DAYS = 0) * 100.0 / COUNT(*), 2) AS SAME_DAY_REPORTING_PERCENTAGE,
    COUNT_IF(CLAIM_AMOUNT >= 50000) AS HIGH_VALUE_CLAIMS,
    ROUND(COUNT_IF(CLAIM_AMOUNT >= 50000) * 100.0 / COUNT(*),  2) AS HIGH_VALUE_CLAIM_PERCENTAGE
FROM INSURANCE_ANALYTICS;



SELECT 
    *
FROM CLAIMS_SUMMARY_VW;



