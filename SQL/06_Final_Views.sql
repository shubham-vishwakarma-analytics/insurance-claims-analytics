-------------------------------------------------------Agent Performance View----------------------------------------------------------


CREATE OR REPLACE VIEW AGENT_PERFORMANCE_VW AS
SELECT
    I.AGENT_ID,
    E.AGENT_NAME,
    COUNT(*) AS CLAIM_COUNT,
    ROUND(SUM(I.CLAIM_AMOUNT), 2)  AS TOTAL_CLAIM_AMOUNT,
    ROUND(AVG(I.CLAIM_AMOUNT), 2)  AS AVG_CLAIM_AMOUNT,
    ROUND(AVG(I.REPORTING_DELAY_DAYS), 2)  AS AVG_REPORTING_DELAY_DAYS,
    COUNT_IF(I.CLAIM_AMOUNT >= 50000) AS HIGH_VALUE_CLAIMS,
    ROUND(COUNT_IF(I.REPORTING_DELAY_DAYS = 0) * 100.0 / COUNT(*), 2) AS SAME_DAY_REPORTING_PERCENTAGE
FROM INSURANCE_ANALYTICS I
LEFT JOIN EMPLOYEE_CLEANED E
    ON I.AGENT_ID = E.AGENT_ID
GROUP BY
    I.AGENT_ID,
    E.AGENT_NAME;

--------------------------- Check--------------------------
SELECT  TOP 10
    *
FROM AGENT_PERFORMANCE_VW
ORDER BY TOTAL_CLAIM_AMOUNT DESC;


---------------------------------------------------------Vendor Performance View----------------------------------------------------------


CREATE OR REPLACE VIEW VENDOR_PERFORMANCE_VW AS
SELECT
    I.VENDOR_ID,
    V.VENDOR_NAME,
    COUNT(*) AS CLAIM_COUNT,
    ROUND(SUM(I.CLAIM_AMOUNT), 2) AS TOTAL_CLAIM_AMOUNT,
    ROUND(AVG(I.CLAIM_AMOUNT), 2) AS AVG_CLAIM_AMOUNT,
    ROUND(AVG(I.REPORTING_DELAY_DAYS), 2) AS AVG_REPORTING_DELAY_DAYS,
    COUNT_IF(I.CLAIM_AMOUNT >= 50000) AS HIGH_VALUE_CLAIMS
FROM INSURANCE_ANALYTICS I
LEFT JOIN VENDOR_CLEANED V
    ON I.VENDOR_ID = V.VENDOR_ID
WHERE I.VENDOR_ID IS NOT NULL
GROUP BY
    I.VENDOR_ID,
    V.VENDOR_NAME;

--------------------------- Check--------------------------
SELECT TOP 10
    *
FROM VENDOR_PERFORMANCE_VW
ORDER BY TOTAL_CLAIM_AMOUNT DESC;




----------------------------------------------- Monthly Claims Trend View ----------------------------------------------------


CREATE OR REPLACE VIEW MONTHLY_CLAIMS_TREND_VW AS
SELECT
    LOSS_YEAR,
    LOSS_MONTH,
    LOSS_MONTH_NAME,
    COUNT(*) AS CLAIM_COUNT,
    ROUND(SUM(CLAIM_AMOUNT), 2) AS TOTAL_CLAIM_AMOUNT,
    ROUND(AVG(CLAIM_AMOUNT), 2) AS AVG_CLAIM_AMOUNT,
    ROUND(AVG(REPORTING_DELAY_DAYS), 2)    AS AVG_REPORTING_DELAY_DAYS,
    SUM(IFF(CLAIM_AMOUNT >= 50000 , 1, 0))  AS HIGH_VALUE_CLAIMS
FROM INSURANCE_ANALYTICS
GROUP BY
    LOSS_YEAR,
    LOSS_MONTH,
    LOSS_MONTH_NAME;

