-----------------------------------------------Investigation Priority View------------------------------------------------------

CREATE OR REPLACE VIEW CLAIM_INVESTIGATION_PRIORITY_VW AS
SELECT
    TRANSACTION_ID,
    POLICY_NUMBER,

    INSURANCE_TYPE,
    STATE,

    RISK_SEGMENTATION,
    INCIDENT_SEVERITY,

    CLAIM_AMOUNT,
    PREMIUM_AMOUNT,
    CLAIM_TO_PREMIUM_RATIO,

    REPORTING_DELAY_DAYS,

    CASE
        WHEN RISK_SEGMENTATION = 'High'
            THEN 1
        ELSE 0
    END AS HIGH_RISK_FLAG,

    CASE
        WHEN CLAIM_AMOUNT >= 50000
            THEN 1
        ELSE 0
    END AS HIGH_VALUE_FLAG,

    CASE
        WHEN CLAIM_TO_PREMIUM_RATIO >= 500
            THEN 1
        ELSE 0
    END AS HIGH_RATIO_FLAG,

    CASE
        WHEN REPORTING_DELAY_DAYS >= 3
            THEN 1
        ELSE 0
    END AS DELAYED_REPORT_FLAG,

    (
        CASE
            WHEN RISK_SEGMENTATION = 'High' THEN 1
            ELSE 0
        END
        +
        CASE
            WHEN CLAIM_AMOUNT >= 50000 THEN 1
            ELSE 0
        END
        +
        CASE
            WHEN CLAIM_TO_PREMIUM_RATIO >= 500 THEN 1
            ELSE 0
        END
        +
        CASE
            WHEN REPORTING_DELAY_DAYS >= 3 THEN 1
            ELSE 0
        END
    ) AS INVESTIGATION_PRIORITY_SCORE

FROM INSURANCE_ANALYTICS;

--Check

SELECT TOP 10
    *
FROM CLAIM_INVESTIGATION_PRIORITY_VW
ORDER BY
    INVESTIGATION_PRIORITY_SCORE DESC,
    CLAIM_AMOUNT DESC;




